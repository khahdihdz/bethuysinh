const CHAR_W = 5;
const SPACING = 1;

// Vẽ chuỗi bằng bitmap font, trả về bề rộng đã vẽ.
export function drawText(ctx, text, x, y, color, scale = 1) {
  const s = String(text).toUpperCase();
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (let i = 0; i < s.length; i++) {
    const glyph = G[s[i]] || G['?'];
    for (let row = 0; row < 7; row++) {
      const line = glyph[row];
      for (let col = 0; col < CHAR_W; col++) {
        if (line[col] === '1') {
          ctx.fillRect(cx + col * scale, cy + row * scale, scale, scale);
        }
      }
    }
    cx += (CHAR_W + SPACING) * scale;
  }
  return cx - x;
}

export function textWidth(text, scale = 1) {
  return String(text).length * (CHAR_W + SPACING) * scale;
}

// Vẽ chuỗi canh phải tại xRight.
export function drawTextRight(ctx, text, xRight, y, color, scale = 1) {
  return drawText(ctx, text, xRight - textWidth(text, scale), y, color, scale);
}
